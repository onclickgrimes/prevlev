import { test, expect, chromium, type Browser, type Page } from "@playwright/test";
import { build } from "esbuild";
import { existsSync } from "node:fs";
let browser: Browser;
let bundle: string;
test.beforeAll(async () => {
  browser = await chromium.launch({ executablePath: process.env.PREVLEV_CHROMIUM_PATH ?? (existsSync("/usr/bin/chromium") ? "/usr/bin/chromium" : undefined), headless: true, args: ["--no-sandbox"] });
  const result = await build({ stdin: { contents: `import { mountMcpGuide } from './src/ui/mcp-guide';
    const copies = []; window.testCopies = copies; window.testGuide = mountMcpGuide(document.querySelector('#host'), { copyText: async text => { copies.push(text); } });`, resolveDir: process.cwd(), loader: "ts" }, bundle: true, write: false, format: "iife" });
  bundle = result.outputFiles[0].text;
});
test.afterAll(async () => { await browser?.close(); });
async function fixture(): Promise<{ page: Page; requests: string[] }> {
  const page = await browser.newPage(), requests: string[] = [];
  await page.route("**/*", async route => { requests.push(route.request().url()); await route.abort(); });
  await page.setContent('<section id="host"></section>');
  await page.addScriptTag({ content: bundle });
  return { page, requests };
}
test("opens without side effects and only copies explicitly prepared manual configuration", async () => {
  const { page, requests } = await fixture();
  await expect(page.locator("#mcp-tools dt")).toHaveCount(5);
  await expect(page.locator("#mcp-guide")).toContainText("Saldo e quota de serviços externos: desconhecidos");
  await expect(page.locator("#mcp-config-output")).toHaveValue("");
  await expect(page.locator("#mcp-copy-config")).toBeDisabled();
  await expect(page.locator("#mcp-guide-status")).toContainText("Nenhuma conexão");
  await page.locator("#mcp-client").selectOption("chatgpt");
  await expect(page.locator("#mcp-client-note")).toContainText("não detecta suporte");
  await page.locator("#mcp-node-path").fill("node");
  await page.locator("#mcp-prepare-config").click();
  await expect(page.locator("#mcp-guide-status")).toContainText("caminho absoluto");
  await page.locator("#mcp-node-path").fill("/opt/node/bin/node");
  await page.locator("#mcp-server-path").fill("/work/Prevlev/server/mcp.mjs");
  await page.locator("#mcp-data-dir").fill("/work/observations");
  await page.locator("#mcp-prepare-config").click();
  expect(JSON.parse(await page.locator("#mcp-config-output").inputValue())).toEqual({ command: "/opt/node/bin/node", args: ["/work/Prevlev/server/mcp.mjs"], env: { MCP_ENABLED: "true", DATA_DIR: "/work/observations", HISTORY_MAX_RECORDS: "5000" } });
  expect(await page.evaluate("window.testCopies")).toEqual([]);
  await page.locator("#mcp-copy-config").click();
  await expect(page.locator("#mcp-guide-status")).toContainText("Nenhum envio ou conexão");
  expect((await page.evaluate("window.testCopies") as string[])).toHaveLength(1);
  await page.locator("#mcp-data-dir").fill("/work/other");
  await expect(page.locator("#mcp-copy-config")).toBeDisabled();
  await expect(page.locator("#mcp-config-output")).toHaveValue("");
  expect(requests).toEqual([]);
  await page.close();
});
test("composes exact tool drafts and refuses API data without network or automatic sending", async () => {
  const { page, requests } = await fixture();
  await page.locator("#mcp-prepare-prompt").click();
  await expect(page.locator("#mcp-prompt-output")).toHaveValue(/prevlev_capabilities/u);
  await page.locator("#mcp-tool").selectOption("history_get");
  await expect(page.locator("#mcp-prompt-output")).toHaveValue("");
  await page.locator("#mcp-prepare-prompt").click();
  await expect(page.locator("#mcp-guide-status")).toContainText("11 caracteres");
  await page.locator("#mcp-video-id").fill("abcdefghijk");
  await page.locator("#mcp-limit").fill("4");
  await page.locator("#mcp-prepare-prompt").click();
  await expect(page.locator("#mcp-prompt-output")).toHaveValue(/"videoId": "abcdefghijk"/u);
  await page.locator("#mcp-copy-prompt").click();
  expect((await page.evaluate("window.testCopies") as string[])).toHaveLength(1);
  await page.locator("#mcp-tool").selectOption("analyze_dataset");
  await page.locator("#mcp-source").selectOption("user-provided");
  await page.locator("#mcp-videos").fill('[{"id":"abcdefghijk","title":"A","source":"youtube-data-api"}]');
  await page.locator("#mcp-prepare-prompt").click();
  await expect(page.locator("#mcp-guide-status")).toContainText("YouTube Data API");
  await expect(page.locator("#mcp-copy-prompt")).toBeDisabled();
  await page.locator("#mcp-feature").selectOption("sponsorships");
  await expect(page.locator("#mcp-videos-label")).toBeHidden();
  await page.locator("#mcp-text").fill('<script>window.untrusted = true</script> Divulgação fornecida por mim.');
  await page.locator("#mcp-prepare-prompt").click();
  await expect(page.locator("#mcp-prompt-output")).toHaveValue(/Divulgação fornecida por mim/u);
  expect(await page.evaluate("window.untrusted")).toBeUndefined();
  expect(requests).toEqual([]);
  expect((await page.evaluate("window.testCopies") as string[])).toHaveLength(1);
  await page.close();
});
